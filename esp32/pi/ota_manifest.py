"""ota_manifest.py - signed firmware-update manifests for the ESP32 sensors (fw 2.4).

A release is one firmware image plus a manifest signed with the dedicated
firmware-signing key (generated in WSL on the publisher machine by
scripts/ota/keygen.sh, ~/.sui-om2m-fw/fw_signing.pem, never copied). Its PUBLIC
key is pinned in the firmware (fw_keys.h, generated by esp32/firmware/gen_fw_keys.sh
from deploy/v9/fw_keys/*.pub). The board accepts an update only if ALL hold:

  * the manifest is signed by a pinned key:
        sig = Ed25519(fw key, FW_DOMAIN || <manifest without the sig field>)
    with a domain tag distinct from the device-signature and ack tags, so no
    other signed message can ever be passed off as a release;
  * kind == "om2m-fw", target == "all" or the board's own device id;
  * version > the version the board runs AND > any version that already failed
    on it (anti-rollback; a release that rolled back is never retried);
  * 0 < size <= the OTA slot size, path matches /fw/<name>.bin;
  * the downloaded image has exactly `size` bytes and SHA-256 `sha256`.

Manifest (compact JSON, "sig" last, every key exactly once):
  {"kind":"om2m-fw","version":240,"target":"all","size":1069968,
   "sha256":"<64 hex>","path":"/fw/fw-240.bin","fpk":"<64 hex>","ts":1763300000,
   "sig":"<128 hex>"}

This module is the reference implementation: the firmware (ota_core.h) mirrors
it byte for byte, the simulator and the tests use it, and scripts/ota/publish.sh
uses `python3 ota_manifest.py body ...` to build the exact body it signs.
"""
import hashlib
import json
import re
import sys

FW_DOMAIN = b"om2m-esp32-fw-v1\x00"
KIND = "om2m-fw"
SIG_FIELD = b',"sig":"'
PATH_RE = re.compile(r"^/fw/[A-Za-z0-9._-]{1,64}\.bin$")
SLOT_SIZE = 0x140000          # one app slot of the ESP32 Dev Module "default" partition table
FIELDS = ("kind", "version", "target", "size", "sha256", "path", "fpk", "ts")


class OtaError(Exception):
    """A rejected manifest or image; str(e) is a short machine-readable reason."""


def body_json(version, size, sha256, path, fpk, target="all", ts=0) -> str:
    """The exact bytes that are signed (key order fixed)."""
    obj = {"kind": KIND, "version": int(version), "target": target, "size": int(size),
           "sha256": sha256.lower(), "path": path, "fpk": fpk.lower(), "ts": int(ts)}
    return json.dumps(obj, separators=(",", ":"))


def sign_manifest(body: str, sk) -> str:
    """sk: cryptography Ed25519PrivateKey (tests). The release path signs with openssl."""
    if not body.endswith("}") or '"sig"' in body:
        raise ValueError("body must be a JSON object without a sig field")
    return body[:-1] + ',"sig":"' + sk.sign(FW_DOMAIN + body.encode()).hex() + '"}'


def load_fw_keys(path: str) -> set:
    """Lines '<label> <64-hex pk>' or bare hex (# comments) -> set of pk hex."""
    out = set()
    with open(path) as f:
        for line in f:
            parts = line.split("#", 1)[0].split()
            if not parts:
                continue
            pk = parts[-1].lower()
            if not re.fullmatch(r"[0-9a-f]{64}", pk):
                raise ValueError(f"{path}: bad firmware key line {parts}")
            out.add(pk)
    return out


def _no_dupes(pairs):
    keys = [k for k, _ in pairs]
    if len(keys) != len(set(keys)):
        raise OtaError("duplicate_field")
    return dict(pairs)


def verify_manifest(raw: bytes, pinned: set) -> dict:
    """-> the verified manifest dict, or OtaError(reason)."""
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    i = raw.rfind(SIG_FIELD)
    if i < 0:
        raise OtaError("unsigned")
    tail = raw[i + len(SIG_FIELD):]
    if len(tail) != 130 or not tail.endswith(b'"}'):
        raise OtaError("bad_sig_format")
    body = raw[:i] + b"}"
    try:
        sig = bytes.fromhex(tail[:128].decode("ascii"))
        msg = json.loads(raw.decode("utf-8"), object_pairs_hook=_no_dupes)
        signed = json.loads(body.decode("utf-8"), object_pairs_hook=_no_dupes)
    except OtaError:
        raise
    except (UnicodeDecodeError, ValueError):
        raise OtaError("malformed")
    if not isinstance(msg, dict) or {k: v for k, v in msg.items() if k != "sig"} != signed:
        raise OtaError("body_mismatch")
    if set(signed) != set(FIELDS):
        raise OtaError("bad_fields")
    fpk = signed.get("fpk")
    if not (isinstance(fpk, str) and fpk.lower() in pinned):
        raise OtaError("untrusted_key")
    try:
        Ed25519PublicKey.from_public_bytes(bytes.fromhex(fpk)).verify(sig, FW_DOMAIN + body)
    except (InvalidSignature, ValueError):
        raise OtaError("bad_signature")
    return signed


def decide(m: dict, device: str, installed: int, bad: int = 0, slot: int = SLOT_SIZE) -> None:
    """Raise OtaError(reason) unless the board should download this release."""
    def is_int(x):
        return isinstance(x, int) and not isinstance(x, bool)
    if m.get("kind") != KIND:
        raise OtaError("wrong_kind")
    if m.get("target") not in ("all", device):
        raise OtaError("not_for_this_device")
    v = m.get("version")
    if not is_int(v) or v <= 0:
        raise OtaError("bad_version")
    if v <= installed:
        raise OtaError("not_newer")           # anti-rollback / already installed
    if v <= bad:
        raise OtaError("failed_before")       # a release that rolled back is not retried
    sz = m.get("size")
    if not is_int(sz) or sz <= 0 or sz > slot:
        raise OtaError("bad_size")
    if not (isinstance(m.get("sha256"), str) and re.fullmatch(r"[0-9a-f]{64}", m["sha256"])):
        raise OtaError("bad_sha256")
    if not (isinstance(m.get("path"), str) and PATH_RE.match(m["path"])):
        raise OtaError("bad_path")


def check_image(m: dict, data: bytes) -> None:
    if len(data) != m["size"]:
        raise OtaError("size_mismatch")
    if hashlib.sha256(data).hexdigest() != m["sha256"]:
        raise OtaError("sha256_mismatch")


def fetch(host: str, port: int, path: str, timeout=20.0, limit=SLOT_SIZE + 1) -> bytes:
    """Plain HTTP/1.0 GET, the same request the firmware sends."""
    import socket
    with socket.create_connection((host, port), timeout=timeout) as s:
        s.sendall(f"GET {path} HTTP/1.0\r\nHost: {host}\r\n\r\n".encode())
        buf = b""
        while True:
            chunk = s.recv(65536)
            if not chunk:
                break
            buf += chunk
            if len(buf) > limit + 4096:
                raise OtaError("too_large")
    head, _, body = buf.partition(b"\r\n\r\n")
    parts = head.split(b"\r\n", 1)[0].split(b" ")
    code = parts[1].decode("latin-1", "replace") if len(parts) > 1 else "error"
    if code != "200":
        raise OtaError("http_" + code)
    return body


def check_release(host, port, device, installed, pinned, bad=0, manifest_raw=None):
    """What a board does: (manifest from the announce, or GET /fw/manifest.json)
    -> verify -> decide -> download -> check. Returns the manifest; OtaError otherwise."""
    raw = manifest_raw if manifest_raw is not None else fetch(host, port, "/fw/manifest.json")
    m = verify_manifest(raw.strip(), pinned)
    decide(m, device, installed, bad)
    check_image(m, fetch(host, port, m["path"]))
    return m


def _main(argv):
    if len(argv) >= 2 and argv[1] == "body":
        # body <version> <size> <sha256> <path> <fpk> <target> <ts>
        v, size, sha, path, fpk, target, ts = argv[2:9]
        sys.stdout.write(body_json(v, size, sha, path, fpk, target, ts))
        return 0
    if len(argv) >= 2 and argv[1] == "check":
        # check <host> <port> <device> <installed> <fw_keys_file> [bad]
        host, port, device, installed, keys = argv[2:7]
        bad = int(argv[7]) if len(argv) > 7 else 0
        try:
            m = check_release(host, int(port), device, int(installed), load_fw_keys(keys), bad)
            print(json.dumps({"result": "accept", "version": m["version"], "size": m["size"]}))
            return 0
        except OtaError as e:
            print(json.dumps({"result": "reject", "reason": str(e)}))
            return 2
    print(__doc__)
    return 1


if __name__ == "__main__":
    sys.exit(_main(sys.argv))
