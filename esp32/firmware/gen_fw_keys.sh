#!/usr/bin/env bash
# gen_fw_keys.sh - pin the firmware-signing PUBLIC key(s) on the ESP32 firmware.
#
# Releases are signed with a dedicated Ed25519 key made by scripts/ota/keygen.sh
# in WSL on the publisher machine (~/.sui-om2m-fw/fw_signing.pem, never copied).
# Its public key is recorded (public data only) as deploy/v9/fw_keys/<label>.pub.
# This script turns that directory into
#   firmware/esp32_sensor_node/fw_keys.h   #define FW_SIGNING_KEYS "hex,..."
#   deploy/v9/fw_keys/trusted.txt          "<label> <hex>" lines (simulator, tests)
# A board accepts only releases signed by a key pinned in the image it RUNS, so
# rotating the key = publish one release (signed by the old key) that pins the new one.
#
#   esp32/firmware/gen_fw_keys.sh
set -euo pipefail
REPO=$(cd "$(dirname "$0")/../.." && pwd)
DIR=$REPO/deploy/v9/fw_keys
OUT=$REPO/esp32/firmware/esp32_sensor_node/fw_keys.h
shopt -s nullglob
files=("$DIR"/*.pub)
[[ ${#files[@]} -gt 0 ]] || { echo "no $DIR/*.pub (run scripts/ota/keygen.sh)"; exit 1; }
(( ${#files[@]} <= 4 )) || { echo "at most 4 firmware keys fit on the board"; exit 1; }
keys=() lines=()
for f in "${files[@]}"; do
  k=$(tr -d '[:space:]' < "$f" | tr 'A-F' 'a-f')
  [[ $k =~ ^[0-9a-f]{64}$ ]] || { echo "$f: not a 64-hex public key"; exit 1; }
  keys+=("$k"); lines+=("$(basename "$f" .pub) $k")
done
csv=$(IFS=,; echo "${keys[*]}")
{
  echo "// Generated by esp32/firmware/gen_fw_keys.sh from deploy/v9/fw_keys/*.pub."
  echo "// PUBLIC firmware-signing key(s): ${#keys[@]}. Do not edit."
  echo "#pragma once"
  echo "#ifndef FW_SIGNING_KEYS"
  echo "#define FW_SIGNING_KEYS \"$csv\""
  echo "#endif"
} > "$OUT"
printf '%s\n' "# label firmware-signing-public-key (generated by gen_fw_keys.sh)" "${lines[@]}" > "$DIR/trusted.txt"
echo "pinned ${#keys[@]} firmware key(s): $OUT, $DIR/trusted.txt"
