#!/usr/bin/env bash
# gen_ack_keys.sh - pin the bridges' ack PUBLIC keys on the ESP32 firmware.
#
# Each bridge signs its acks with its own Ed25519 key, generated on its Pi by
# pi/install.sh and never copied. Its public key is recorded (public data only)
# as deploy/v9/ack_keys/<node>.pub, one 64-hex line. This script turns that
# directory into
#   firmware/esp32_sensor_node/ack_keys.h   #define ACK_TRUSTED_KEYS "hex,hex,..."
#   deploy/v9/ack_keys/trusted.txt          "<node> <hex>" lines (simulator --ack-keys)
# Re-run it and reflash the boards when a node is added or its ack key changes.
#
#   esp32/firmware/gen_ack_keys.sh            (from anywhere in the repo)
set -euo pipefail
REPO=$(cd "$(dirname "$0")/../.." && pwd)
DIR=$REPO/deploy/v9/ack_keys
OUT=$REPO/esp32/firmware/esp32_sensor_node/ack_keys.h
shopt -s nullglob
files=("$DIR"/*.pub)
[[ ${#files[@]} -gt 0 ]] || { echo "no $DIR/*.pub"; exit 1; }
(( ${#files[@]} <= 16 )) || { echo "at most 16 ack keys fit on the board"; exit 1; }
keys=() lines=()
for f in "${files[@]}"; do
  k=$(tr -d '[:space:]' < "$f" | tr 'A-F' 'a-f')
  [[ $k =~ ^[0-9a-f]{64}$ ]] || { echo "$f: not a 64-hex public key"; exit 1; }
  n=$(basename "$f" .pub)
  keys+=("$k"); lines+=("$n $k")
done
csv=$(IFS=,; echo "${keys[*]}")
{
  echo "// Generated by esp32/firmware/gen_ack_keys.sh from deploy/v9/ack_keys/*.pub."
  echo "// PUBLIC keys of the bridges' ack signers: ${#keys[@]} node(s). Do not edit."
  echo "#pragma once"
  echo "#ifndef ACK_TRUSTED_KEYS"
  echo "#define ACK_TRUSTED_KEYS \"$csv\""
  echo "#endif"
} > "$OUT"
printf '%s\n' "# label ack-public-key (generated by gen_ack_keys.sh)" "${lines[@]}" > "$DIR/trusted.txt"
echo "pinned ${#keys[@]} ack key(s): $OUT, $DIR/trusted.txt"
