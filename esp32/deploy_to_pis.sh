#!/usr/bin/env bash
# deploy_to_pis.sh - run from the laptop (Git Bash or WSL) while on the AUS
# network / VPN. Nodes come from deploy/inventory.tsv (scripts/lib/inventory.sh),
# the single node list of the testbed; nothing here hard-codes a node.
# SSH key auth only (~/.ssh/id_ed25519_suiom2m, user `user`).
#
#   ./deploy_to_pis.sh check              reachability + what the bridge needs, changes nothing
#   ./deploy_to_pis.sh members            write pi/members.conf from the inventory
#   ./deploy_to_pis.sh install rpi2       install/upgrade the bridge on ONE node + smoke test
#   ./deploy_to_pis.sh install all        then every active node
#   ./deploy_to_pis.sh status             service state + last log lines on every active node
#
# Never restarts, recreates or edits the OM2M container, sui.properties,
# sui.mappings.properties or the broker mesh. The bridge only ADDS device AEs.
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/.." && pwd)
# shellcheck disable=SC1091
. "$REPO/scripts/lib/inventory.sh"
inv_load
# ssh_config generated by inventory.sh: key auth, user `user`, and ProxyJump
# for nodes behind a jump host (rpi4/rpi5 via rpi1).
SSH_OPTS=(-F "$INV_SSH_CONFIG" -o BatchMode=yes -o ConnectTimeout=10)
on() { ssh "${SSH_OPTS[@]}" "$1" "${@:2}"; }
ACTIVE=$(inv_nodes active)
pick() { if [[ "${1:-all}" == all ]]; then echo $ACTIVE; else inv_require "$1"; echo "$1"; fi; }

case "${1:-check}" in
check)
  for n in $ACTIVE; do
    echo "== $n (${INV_IP[$n]})"
    if ! on "$n" true 2>/dev/null; then echo "   SSH: unreachable (VPN? key installed?)"; continue; fi
    on "$n" 'J="Accept: application/json"; O="X-M2M-Origin: admin:admin"; B=http://127.0.0.1:8282
      echo "   SSH: ok ($(hostname))"
      echo "   OM2M: $(curl -s -o /dev/null -w %{http_code} -H "$O" $B/~/in-cse)  (want 200)"
      for r in acp_sui_dac sui-dac sui-das; do
        echo "   $r: $(curl -s -o /dev/null -w %{http_code} -H "$O" -H "$J" $B/~/in-cse/in-name/$r)  (want 200: provision-das.sh Part B)"
      done
      echo "   containers: $(docker ps --format "{{.Names}}" | tr "\n" " ")"
      echo "   mqtt 1883: $( (exec 3<>/dev/tcp/127.0.0.1/1883) 2>/dev/null && echo open || echo closed)"
      echo "   python deps: $(python3 -c "import paho.mqtt, requests; print(\"ok\")" 2>/dev/null || echo "missing (install.sh adds them)")"
      echo "   cluster id: $(grep -E "^sui.failover.cluster.id=" ~/sui-runtime-config/sui.properties 2>/dev/null | cut -d= -f2 | cut -c1-12)..."
      echo "   bridge: $(systemctl is-active om2m-ipe-bridge 2>/dev/null)"'
    # the bridge writes to the PARENT's CSE: every node must reach every node's :8282
    for m in $(inv_peers_of "$n"); do
      code=$(on "$n" "curl -s -m 3 -o /dev/null -w %{http_code} -H 'X-M2M-Origin: admin:admin' http://${INV_IP[$m]}:8282/~/in-cse" 2>/dev/null)
      echo "   -> $m :8282 from $n: ${code:-000}"
    done
  done
  pend=$(inv_nodes pending staged | tr '\n' ' ')
  [[ -n "$pend" ]] && echo "(not active yet, skipped: $pend)" ;;
members)
  OUT="$HERE/pi/members.conf"
  { echo "# generated by deploy_to_pis.sh members from deploy/inventory.tsv, $(date -u +%FT%TZ)"
    echo "# the same file on every node; label host mqtt cse-url sui-address"
    for n in $(inv_nodes all); do
      [[ ${INV_STATUS[$n]} == pending ]] && echo "# $n: pending onboarding (listed so sensors can learn it once active)"
      echo "$n ${INV_IP[$n]} 1883 http://${INV_IP[$n]}:8282 ${INV_ADDR[$n]}"
    done; } > "$OUT"
  cat "$OUT" ;;
install)
  [[ -f "$HERE/pi/members.conf" ]] || "$0" members >/dev/null
  for n in $(pick "${2:-}"); do
    [[ ${INV_STATUS[$n]} == active ]] || { echo "!! $n is ${INV_STATUS[$n]}, not active: onboard it first"; exit 1; }
    echo "== installing on $n"
    on "$n" "rm -rf ~/esp32-bridge-pkg && mkdir -p ~/esp32-bridge-pkg" && \
    scp "${SSH_OPTS[@]}" -q -r "$HERE/pi/." "$n:~/esp32-bridge-pkg/" && \
    on "$n" "cd ~/esp32-bridge-pkg && chmod +x *.sh && sudo ./install.sh $n && ./smoke_test.sh" \
      || { echo "!! install on $n failed; stopping here"; exit 1; }
  done ;;
status)
  for n in $ACTIVE; do
    echo "== $n"
    on "$n" 'systemctl is-active om2m-ipe-bridge; journalctl -u om2m-ipe-bridge -n 6 --no-pager -o cat' 2>/dev/null \
      || echo "   unreachable"
  done ;;
*) echo "usage: $0 check | members | install <node|all> | status" ;;
esac
