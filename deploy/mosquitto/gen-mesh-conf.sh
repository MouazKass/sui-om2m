#!/bin/bash
# Generates a per-node mosquitto.conf for the loop-free broker mesh.
# Usage: gen-mesh-conf.sh <self-ip> <self-sui-address> <peer-ip> [<peer-ip>...]
#   one out-only bridge per peer; any cluster size (callers take the peers from
#   deploy/inventory.tsv via scripts/lib/inventory.sh).
#
# Why the topology changed (2026-11-10)
# -------------------------------------
# The old config bridged `om2m/trust/obs/#` and `om2m/failover/#` in BOTH
# directions from every broker to both peers. That connects each pair twice and
# makes the three brokers a cycle. MQTT has no TTL, so every message was
# re-forwarded forever. Measured on the live mesh: ~213,000 deliveries per 8 s
# carrying only 110 distinct payloads, with messages from long-stopped
# publishers still circulating months later. Worse, a dead parent's heartbeats
# kept circulating and made it look alive to failover.
#
# Loop-free design: per-origin topics. Each node PUBLISHES only on
#     om2m/trust/obs/<cluster>/<its-own-address>
#     om2m/failover/heartbeat/<cluster>/<its-own-address>
# and SUBSCRIBES to .../<cluster>/+ (see TrustGossip, FailoverManager). Each
# bridge forwards ONLY this node's own subtree, OUT. A message from A reaches B
# directly, and B's bridges don't match A's subtree, so it is never forwarded
# again. Full mesh, no hub, no cycle, no amplification.
SELF=${1:-}; SELF_ADDR=$(echo "${2:-}" | tr 'A-F' 'a-f'); shift 2 2>/dev/null || true
PEERS=("$@")
[ -n "$SELF" ] && [ -n "$SELF_ADDR" ] && [ ${#PEERS[@]} -ge 1 ] || {
  echo "usage: $0 <self-ip> <self-sui-address> <peer-ip> [<peer-ip>...]" >&2; exit 1; }
for p in "${PEERS[@]}"; do
  [ "$p" != "$SELF" ] || { echo "$0: a node must not bridge to itself ($p)" >&2; exit 1; }
done
[ "$(printf '%s
' "${PEERS[@]}" | sort | uniq -d)" = "" ] || { echo "$0: duplicate peer" >&2; exit 1; }

bridge() {
cat <<CONF
# --- Bridge to $1: forward only this node's own messages ---
connection bridge-${SELF}-to-$1
address $1:1883
topic om2m/trust/obs/+/${SELF_ADDR} out 0
topic om2m/failover/heartbeat/+/${SELF_ADDR} out 0
bridge_attempt_unsubscribe false
restart_timeout 5
cleansession true

CONF
}

cat <<CONF
# Generated by deploy/mosquitto/gen-mesh-conf.sh for node $SELF ($SELF_ADDR).
listener 1883 0.0.0.0
allow_anonymous true
persistence true
persistence_location /mosquitto/data/

CONF
for p in "${PEERS[@]}"; do bridge "$p"; done
