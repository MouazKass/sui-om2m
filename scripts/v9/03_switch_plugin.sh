#!/usr/bin/env bash
# 03_switch_plugin.sh - V9_DESIGN.md phase F: point the three Pis at v9 (or back).
#
# Run from Git Bash on the laptop (like scripts/v8/04_cutover.sh, which it drives).
#
#   03_switch_plugin.sh status     what the generated config targets now; read-only
#   03_switch_plugin.sh v9         sui.package.id -> PKG_V9, then config/redeploy/verify
#                                  and prove a v9 MoveCall lands from the nodes
#   03_switch_plugin.sh flush-on   after a verified v9 GRANT: turn on the on-chain
#                                  DENY batch flush (F3), then config/redeploy
#   03_switch_plugin.sh v8         roll back to v8 (allowed only BEFORE phase G;
#                                  once governed, v8 cap paths abort by design)
#
# How: writes deploy/v9/plugin-target.env, which scripts/v8/03_gen_config.sh
# reads (CALL_PKG, DENY_FLUSH). sui.package.original.id stays PKG_V8 always:
# Move type names keep the original package id across upgrades. Idempotent:
# re-running a mode that is already in effect skips regeneration and redeploy
# and only re-verifies.
set -euo pipefail
. "$(dirname "$0")/lib.sh"
CMD="${1:-status}"
TARGET="$V9_DIR/plugin-target.env"
CUTOVER="$REPO/scripts/v8/04_cutover.sh"
NODE_ADDRS=(0xef9c6271d8c6cc9e1d9707a117f876e7a8679509f141879bc05ae7bcffe1d5f9
            0x4be6060abaff0b4b6b7229558887f5f054cbe7d9836ba56eff35d848e13dc1f5
            0x27dacda1bdcb3fb8dc2a4b0d77b420deea5bb43d1047592ddadb19f35764ea10)

gql() {
  curl -sS --max-time 20 "$GRAPHQL_URL" -H 'content-type: application/json' --data-binary @-
}

# Newest successful tx calling package $1 sent by one of our nodes, after ISO time $2.
v9_calls_since() {
  printf '{"query":"{ transactions(last: 20, filter: {function: \\"%s\\"}) { nodes { digest sender { address } effects { timestamp status } } } }"}' "$1" | gql \
  | python3 -c '
import json,sys
nodes=set(a.lower() for a in sys.argv[2:])
since=sys.argv[1]
d=json.load(sys.stdin)["data"]["transactions"]["nodes"]
hits=[t for t in d if t["sender"]["address"].lower() in nodes and t["effects"]["timestamp"]>=since and t["effects"]["status"]=="SUCCESS"]
for t in hits: print(t["effects"]["timestamp"], t["sender"]["address"][:10], t["digest"])
sys.exit(0 if hits else 1)' "$2" "${NODE_ADDRS[@]}"
}

current() { [ -f "$TARGET" ] && cat "$TARGET" || echo "(no $TARGET: plugin targets v8)"; }

write_target() {   # $1 CALL_PKG  $2 DENY_FLUSH
  local want; want=$(printf '# GENERATED by scripts/v9/03_switch_plugin.sh. Read by scripts/v8/03_gen_config.sh.\nCALL_PKG=%s\nDENY_FLUSH=%s\n' "$1" "$2")
  if [ -f "$TARGET" ] && [ "$(grep -v '^#' "$TARGET")" = "$(printf '%s' "$want" | grep -v '^#')" ]; then
    echo "already targeting CALL_PKG=$1 DENY_FLUSH=$2"; return 1
  fi
  printf '%s\n' "$want" > "$TARGET"; echo "wrote $TARGET"; return 0
}

roll() {           # regenerate + upload + redeploy + verify
  say "config -> redeploy -> verify (scripts/v8/04_cutover.sh)"
  bash "$CUTOVER" config
  bash "$CUTOVER" redeploy
  bash "$CUTOVER" verify
}

case "$CMD" in
  status)
    say "plugin target"; current
    for n in 1 2 3; do
      f="$REPO/deploy/v8/nodes/rpi$n/sui.properties"
      echo "rpi$n: $(grep -E '^sui.package.id=' "$f") $(grep -E '^sui.das.deny.audit.flush.enabled=' "$f")"
    done
    ;;

  v9|flush-on)
    [ -n "${PKG_V9:-}" ] || die "no PKG_V9 in $V9_ENV; run 02_upgrade.sh execute first"
    say "check $PKG_V9 on-chain"; check_v9_package "$PKG_V9"
    flush=false; [ "$CMD" = flush-on ] && flush=true
    if [ "$flush" = true ] && [ -z "${V9_GRANT_VERIFIED:-}" ]; then
      die "flush-on needs a verified v9 GRANT first: run '$0 v9' (it records V9_GRANT_VERIFIED)"
    fi
    since=$(date -u +%FT%TZ)
    if write_target "$PKG_V9" "$flush"; then roll; else bash "$CUTOVER" verify; fi
    say "proof the nodes now call v9 (waits up to 15 min: lease renewals every 10 min, GRANTs on demand)"
    for i in $(seq 1 30); do
      if v9_calls_since "$PKG_V9" "$since"; then
        [ "$CMD" = v9 ] && record V9_GRANT_VERIFIED "$(date -u +%FT%TZ)"
        echo "OK: v9 calls landing from the nodes"; exit 0
      fi
      sleep 30
    done
    die "no successful v9 call from any node within 15 min; run '$0 v8' to roll back (pre-phase-G only)"
    ;;

  v8)
    if [ -n "${COUNCIL:-}" ]; then
      die "governance is armed (COUNCIL=$COUNCIL): v8 cap paths now abort by design; roll forward instead (V9_DESIGN.md I)"
    fi
    if [ -f "$TARGET" ]; then rm -f "$TARGET"; echo "removed $TARGET"; roll
    else echo "already on v8"; bash "$CUTOVER" verify; fi
    ;;

  *) sed -n '2,20p' "$0"; exit 1;;
esac
